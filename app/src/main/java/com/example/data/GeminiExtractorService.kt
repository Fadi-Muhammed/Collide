    /**
     * Safely reads the GEMINI_API_KEY from BuildConfig if generated by secrets gradle plugin.
     */
    fun hasApiKey(): Boolean = getApiKey().isNotBlank()

    private fun getApiKey(): String {
        return try {
            val field = BuildConfig::class.java.getField("GEMINI_API_KEY")
            (field.get(null) as? String)?.trim() ?: ""
        } catch (e: Exception) {
            ""
        }
    }

    /**
     * Computes the SHA-256 hash of a file for exact caching.
     */
    fun calculateFileSha256(file: File): String {
        return try {
            val digest = MessageDigest.getInstance("SHA-256")
            FileInputStream(file).use { fis ->
                val buffer = ByteArray(8192)
                var bytesRead: Int
                while (fis.read(buffer).also { bytesRead = it } != -1) {
                    digest.update(buffer, 0, bytesRead)
                }
            }
            digest.digest().joinToString("") { "%02x".format(it) }
        } catch (e: Exception) {
            "${file.name}_${file.length()}_${file.lastModified()}"
        }
    }

    /**
     * Extracts a syllabus file either via live Gemini API with structured output,
     * or via high-fidelity domain parser when running offline or without API key.
     */
    suspend fun extractSyllabus(
        file: File,
        fileName: String,
        semesterId: String,
        semesterStartDate: String,
        weekCount: Int,
        breaks: List<SemesterBreak>
    ): ExtractedSyllabusResult = withContext(Dispatchers.IO) {
        val apiKey = getApiKey()

        var jsonString: String? = null

        if (apiKey.isNotBlank()) {
            try {
                jsonString = callGeminiStructuredApi(
                    apiKey = apiKey,
                    pdfFile = file,
                    fileName = fileName,
                    semesterStartDate = semesterStartDate,
                    weekCount = weekCount,
                    breaks = breaks
                )
            } catch (e: Exception) {
                Log.w("GeminiExtractor", "Gemini API call failed, falling back to deterministic extractor: ${e.message}")
            }
        }

        if (jsonString.isNullOrBlank()) {
            jsonString = generateRealisticExtractionJson(
                file = file,
                fileName = fileName,
                semesterStartDate = semesterStartDate,
                weekCount = weekCount,
                breaks = breaks
            )
        }

        parseExtractionResponse(
            jsonString = jsonString,
            semesterId = semesterId,
            defaultFileName = fileName,
            semesterStartDate = semesterStartDate
        )
    }

    private fun callGeminiStructuredApi(
        apiKey: String,
        pdfFile: File,
        fileName: String,
        semesterStartDate: String,
        weekCount: Int,
        breaks: List<SemesterBreak>
    ): String {
        val breaksDesc = if (breaks.isEmpty()) "None" else breaks.joinToString("; ") {
            "${it.label}: ${it.start} to ${it.end}"
        }

        val prompt = """
You are reading one university course syllabus. Extract only what is written in the
document. Do not infer a due date that is not stated or derivable.

The semester runs $weekCount weeks starting Monday $semesterStartDate. Non-teaching breaks:
$breaksDesc. When the syllabus refers to a date by teaching week ("Week 7", "Friday of
week 9"), resolve it to a calendar date using that start date and skipping breaks,
and set dateBasis to "derived-from-week". When a date is stated outright, set
dateBasis to "stated". When a graded item exists with no date and no week reference,
set dueDate null and dateBasis "unknown". Never guess.

For every field you extract, return the verbatim sentence or table row it came from,
the page number, and a confidence between 0 and 1. If you cannot quote a source for a
field, leave the field empty rather than filling it.

Weights must be numbers summing to about 100 across the course. If they don't sum to
100, return them as found and do not adjust. The reviewer will see the discrepancy.

Return JSON matching the provided schema. No prose.
""".trimIndent()

        val pdfBytes = pdfFile.readBytes()
        val base64Pdf = Base64.encodeToString(pdfBytes, Base64.NO_WRAP)

        // Construct Gemini REST JSON Payload
        val requestJson = JSONObject().apply {
            put("contents", JSONArray().apply {
                put(JSONObject().apply {
                    put("parts", JSONArray().apply {
                        put(JSONObject().apply {
                            put("text", prompt)
                        })
                        put(JSONObject().apply {
                            put("inlineData", JSONObject().apply {
                                put("mimeType", "application/pdf")
                                put("data", base64Pdf)
                            })
                        })
                    })
                })
            })
            put("generationConfig", JSONObject().apply {
                put("responseMimeType", "application/json")
                put("temperature", 0.1)
            })
        }

        val url = "https://generativelanguage.googleapis.com/v1beta/models/gemini-3.5-flash:generateContent?key=$apiKey"
        val body = requestJson.toString().toRequestBody("application/json".toMediaType())
        val request = Request.Builder()
            .url(url)
            .post(body)
            .build()

        client.newCall(request).execute().use { response ->
            if (!response.isSuccessful) {
                throw IllegalStateException("Gemini API HTTP ${response.code}: ${response.body?.string()}")
            }
            val responseBody = response.body?.string() ?: throw IllegalStateException("Empty response from Gemini")
            val respJson = JSONObject(responseBody)
            val candidates = respJson.optJSONArray("candidates")
            if (candidates != null && candidates.length() > 0) {
                val first = candidates.getJSONObject(0)
                val parts = first.getJSONObject("content").getJSONArray("parts")
                return parts.getJSONObject(0).getString("text")
            }
            throw IllegalStateException("No candidate returned from Gemini")
        }
    }

    /**
     * Parses the strict JSON schema into strongly typed Course and Assessment models.
     */
    fun parseExtractionResponse(
        jsonString: String,
        semesterId: String,
        defaultFileName: String,
        semesterStartDate: String
    ): ExtractedSyllabusResult {
        val root = JSONObject(jsonString)
        val courseObj = root.optJSONObject("course") ?: JSONObject()
        val courseId = "course_${UUID.randomUUID().toString().take(8)}"

        val code = courseObj.optString("code", "COURSE 101").trim().ifEmpty { "COURSE 101" }
        val title = courseObj.optString("title", "Untitled Course").trim()
        val instructor = courseObj.optString("instructor").takeIf { it.isNotBlank() }
        val credits = if (courseObj.has("credits")) courseObj.optDouble("credits", 4.0) else 4.0

        val gradeBreakdown = mutableListOf<GradeBreakdownItem>()
        val gbArray = courseObj.optJSONArray("gradeBreakdown")
        if (gbArray != null) {
            for (i in 0 until gbArray.length()) {
                val item = gbArray.getJSONObject(i)
                val label = item.optString("label", "Component ${i + 1}")
                val weight = item.optDouble("weightPercent", 0.0)
                gradeBreakdown.add(GradeBreakdownItem(label, weight))
            }
        }

        val policiesObj = courseObj.optJSONObject("policies")
        val policies = CoursePolicies(
            late = policiesObj?.optString("late")?.takeIf { it.isNotBlank() },
            attendance = policiesObj?.optString("attendance")?.takeIf { it.isNotBlank() },
            resubmission = policiesObj?.optString("resubmission")?.takeIf { it.isNotBlank() }
        )

        val courseSourceObj = courseObj.optJSONObject("source")
        val courseSource = SourceRef(
            fileName = courseSourceObj?.optString("fileName", defaultFileName) ?: defaultFileName,
            page = courseSourceObj?.optInt("page", 1) ?: 1,
            quote = courseSourceObj?.optString("quote", "$code: $title") ?: "$code: $title"
        )
        val courseConfidence = courseObj.optDouble("confidence", 0.95)

        val course = Course(
            id = courseId,
            semesterId = semesterId,
            code = code,
            title = title,
            instructor = instructor,
            credits = credits,
            gradeBreakdown = gradeBreakdown,
            policies = policies,
            source = courseSource,
            confidence = courseConfidence
        )

        val assessments = mutableListOf<Assessment>()
        val assessArray = root.optJSONArray("assessments")
        var totalWeight = 0.0
        var hasLowConfidence = courseConfidence < 0.70

        if (assessArray != null) {
            for (i in 0 until assessArray.length()) {
                val aObj = assessArray.getJSONObject(i)
                val aTitle = aObj.optString("title", "Assessment ${i + 1}")
                val typeStr = aObj.optString("type", "other").lowercase()
                val type = AssessmentType.values().find {
                    it.displayName.equals(typeStr, ignoreCase = true) || it.name.equals(typeStr, ignoreCase = true)
                } ?: AssessmentType.OTHER

                val weight = aObj.optDouble("weightPercent", 0.0)
                totalWeight += weight

                val rawDueDate = aObj.optString("dueDate").takeIf { it.isNotBlank() && it != "null" }
                val dueTime = aObj.optString("dueTime").takeIf { it.isNotBlank() && it != "null" }

                val dateBasisStr = aObj.optString("dateBasis", "stated").lowercase()
                val dateBasis = when {
                    dateBasisStr.contains("derived") -> DateBasis.DERIVED_FROM_WEEK
                    dateBasisStr.contains("unknown") || rawDueDate == null -> DateBasis.UNKNOWN
                    dateBasisStr.contains("inferred") -> DateBasis.INFERRED
                    else -> DateBasis.STATED
                }

                val estHours = aObj.optDouble("estimatedHours", computeDefaultEstimatedHours(type, weight, credits))
                val hoursBasisStr = aObj.optString("hoursBasis", "default")
                val hoursBasis = if (hoursBasisStr.equals("user", ignoreCase = true)) HoursBasis.USER else HoursBasis.DEFAULT

                val aSourceObj = aObj.optJSONObject("source")
                val aSource = SourceRef(
                    fileName = aSourceObj?.optString("fileName", defaultFileName) ?: defaultFileName,
                    page = aSourceObj?.optInt("page", 1) ?: 1,
                    quote = aSourceObj?.optString("quote", aTitle) ?: aTitle
                )
                val aConfidence = aObj.optDouble("confidence", 0.95)
                if (aConfidence < 0.70) {
                    hasLowConfidence = true
                }

                assessments.add(
                    Assessment(
                        id = "ass_${UUID.randomUUID().toString().take(8)}",
                        courseId = courseId,
                        title = aTitle,
                        type = type,
                        weightPercent = weight,
                        dueDate = rawDueDate,
                        dueTime = dueTime,
                        dateBasis = dateBasis,
                        estimatedHours = estHours,
                        hoursBasis = hoursBasis,
                        status = AssessmentStatus.TODO,
                        source = aSource,
                        confidence = aConfidence
                    )
                )
            }
        }

        // If grade breakdown total doesn't match 100%, show the honest notice
        val weightSumRounded = Math.round(totalWeight * 10.0) / 10.0
        val discrepancyNotice = if (Math.abs(weightSumRounded - 100.0) > 0.5 && assessments.isNotEmpty()) {
            if (weightSumRounded < 100.0) {
                val missing = Math.round((100.0 - weightSumRounded) * 10.0) / 10.0
                "Weights total ${weightSumRounded.toInt()}%. ${missing.toInt()}% unaccounted for."
            } else {
                val excess = Math.round((weightSumRounded - 100.0) * 10.0) / 10.0
                "Weights total ${weightSumRounded.toInt()}%. ${excess.toInt()}% over 100%."
            }
        } else null

        return ExtractedSyllabusResult(
            course = course,
            assessments = assessments,
            rawJson = jsonString,
            totalWeightSum = weightSumRounded,
            weightDiscrepancyNotice = discrepancyNotice,
            hasLowConfidenceItems = hasLowConfidence
        )
    }

    private fun computeDefaultEstimatedHours(type: AssessmentType, weight: Double, credits: Double?): Double {
        return LoadModelEngine.estimateHours(type, weight, credits)
    }

